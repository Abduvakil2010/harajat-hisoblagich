import 'package:drift/drift.dart';

import '../../core/money/currency.dart';
import '../models/enums.dart';

@DataClassName('CategoryRecord')
class Categories extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Stable key for built-in categories (localized at display time).
  TextColumn get key => text().nullable().unique()();

  /// User supplied name for custom categories.
  TextColumn get name => text().nullable().withLength(max: 40)();
  TextColumn get type => textEnum<TransactionType>()();
  TextColumn get iconKey => text()();
  IntColumn get color => integer()();
  BoolColumn get isDefault => boolean().withDefault(const Constant(false))();
  IntColumn get sortOrder => integer().withDefault(const Constant(0))();
}

@DataClassName('TransactionRecord')
@TableIndex(name: 'idx_tx_date', columns: {#date})
@TableIndex(name: 'idx_tx_category', columns: {#categoryId})
class Transactions extends Table {
  /// Amounts/rates must be strictly positive (enforced by SQLite).
  @override
  List<String> get customConstraints => const ['CHECK (amount_minor > 0)'];

  TextColumn get id => text()();
  TextColumn get title => text().withLength(min: 1, max: 80)();

  /// Always positive; the sign is given by [type].
  IntColumn get amountMinor => integer()();
  TextColumn get currency => textEnum<Currency>()();
  IntColumn get categoryId => integer().references(Categories, #id)();
  DateTimeColumn get date => dateTime()();
  TextColumn get description => text().nullable()();
  TextColumn get paymentMethod => textEnum<PaymentMethod>()();
  TextColumn get type => textEnum<TransactionType>()();

  /// Unicode-lowercased title + description, maintained by the repository.
  /// SQLite's `lower()` only folds ASCII, so Cyrillic search needs this.
  TextColumn get searchText => text().withDefault(const Constant(''))();

  /// Set when generated by a recurring payment.
  TextColumn get recurringId => text().nullable()();

  /// `<recurringId>@<yyyy-MM-dd>` – unique, prevents duplicate occurrences.
  TextColumn get occurrenceKey => text().nullable().unique()();
  DateTimeColumn get createdAt => dateTime()();
  DateTimeColumn get updatedAt => dateTime()();

  @override
  Set<Column> get primaryKey => {id};
}

@DataClassName('BudgetRecord')
class Budgets extends Table {
  /// Amounts/rates must be strictly positive (enforced by SQLite).
  @override
  List<String> get customConstraints => const ['CHECK (limit_minor > 0)'];

  IntColumn get id => integer().autoIncrement()();

  /// Null = total monthly budget; otherwise a category limit.
  IntColumn get categoryId => integer().nullable().references(
    Categories,
    #id,
    onDelete: KeyAction.cascade,
  )();
  IntColumn get limitMinor => integer()();
  TextColumn get currency => textEnum<Currency>()();
  DateTimeColumn get createdAt => dateTime()();
  DateTimeColumn get updatedAt => dateTime()();
}

